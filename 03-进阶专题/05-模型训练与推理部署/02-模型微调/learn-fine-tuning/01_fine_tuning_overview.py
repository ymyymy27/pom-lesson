print("\n--- 5. 成本估算 ---")

def estimate_training_cost(data_size: int, epochs: int, model_size: str) -> dict:
    """估算微调成本"""
    configs = {
        "7B-LoRA":  {"gpu": "RTX 4090 (24GB)", "hours_per_1k": 0.5, "gpu_cost_hr": 1.0},
        "7B-QLoRA": {"gpu": "RTX 3060 (12GB)", "hours_per_1k": 0.8, "gpu_cost_hr": 0.5},
        "13B-LoRA": {"gpu": "A100 (40GB)",     "hours_per_1k": 1.0, "gpu_cost_hr": 2.0},
        "OpenAI":   {"gpu": "Cloud",           "hours_per_1k": 0.0, "gpu_cost_hr": 0.0},
    }
    cfg = configs.get(model_size, configs["7B-QLoRA"])
    hours = (data_size / 1000) * cfg["hours_per_1k"] * epochs
    if model_size == "OpenAI":
        # OpenAI 按 token 收费
        tokens = data_size * 500  # 平均每条500 token
        cost = tokens * epochs * 8 / 1_000_000  # gpt-4o-mini 训练价格
    else:
        cost = hours * cfg["gpu_cost_hr"]
    return {"gpu": cfg["gpu"], "hours": hours, "cost_usd": cost}

