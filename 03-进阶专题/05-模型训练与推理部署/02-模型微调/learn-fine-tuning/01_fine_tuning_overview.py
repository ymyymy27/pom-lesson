print("""
Prompt Engineering 的局限：

  ❌ 上下文窗口有限，不能塞入所有领域知识
  ❌ 输出风格/格式控制不够稳定
  ❌ 每次调用都要传长 Prompt，成本高
  ❌ 无法真正学习新知识/新模式
  ❌ 延迟高（长 Prompt = 更多 token）

微调解决的问题：

  ✅ 将知识"烧录"到模型参数中
  ✅ 稳定的输出风格和格式
  ✅ 推理时不需要长 Prompt，成本低
  ✅ 真正学习领域专业知识和模式
  ✅ 更低的推理延迟

典型场景：
  • 客服机器人 → 学习公司的FAQ和话术风格
  • 医疗助手 → 学习专业医学知识和诊断逻辑
  • 代码助手 → 学习特定框架/代码风格
  • 法律顾问 → 学习法律术语和案例分析
  • 多语言翻译 → 学习特定领域的翻译偏好
""")

