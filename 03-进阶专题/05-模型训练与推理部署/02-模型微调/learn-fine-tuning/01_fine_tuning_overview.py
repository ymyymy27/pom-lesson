print(f"  {'场景':<20} {'GPU':^20} {'时间':>6} {'成本':>8}")
print(f"  {'-'*60}")
for name, size, epochs, model in scenarios:
    est = estimate_training_cost(size, epochs, model)
    print(f"  {name:<20} {est['gpu']:^20} {est['hours']:>5.1f}h ${est['cost_usd']:>6.1f}")

