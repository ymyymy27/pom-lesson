# ============================================================================
print("\n--- 2. 扩散模型原理 ---")
print("""
扩散模型的核心思想：

  前向过程（加噪）：
    清晰图像 → 加一点噪声 → 再加 → ... → 纯噪声
    x₀ ────→ x₁ ────→ x₂ ────→ ... → xₜ (纯高斯噪声)

  反向过程（去噪）= 生成过程：
    纯噪声 → 去一点噪声 → 再去 → ... → 清晰图像
    xₜ ────→ xₜ₋₁ ────→ ... ────→ x₁ → x₀ (生成的图像)

  训练目标：学习每一步如何去噪
  推理时：从随机噪声开始，逐步去噪得到图像

Stable Diffusion 的创新——潜空间扩散：
  原始图像(512×512×3) → VAE编码器 → 潜空间(64×64×4) → 在潜空间去噪
  大大减少计算量！

  ┌───────────┐    ┌──────────┐    ┌───────────┐    ┌──────────┐
  │ 文本Prompt │ →  │ CLIP     │ →  │ UNet/DiT  │ →  │ VAE      │
  │ "一只猫"   │    │ 文本编码 │    │ 去噪网络  │    │ 解码器   │
  └───────────┘    └──────────┘    └───────────┘    └──────────┘
                    文本嵌入         潜空间去噪        潜空间→图像

Classifier-Free Guidance (CFG)：
  同时预测有条件和无条件的噪声，加权组合
  CFG scale 越高 → 越遵循提示词（但可能过度饱和）
  通常 CFG=7-12 效果最好
""")

