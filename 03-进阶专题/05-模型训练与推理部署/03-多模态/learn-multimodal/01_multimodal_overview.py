# ============================================================================
print("\n--- 2. 融合原理 ---")
print("""
多模态融合的三种方式：

1. 早期融合（Early Fusion）
   各模态原始数据 → 拼接 → 统一编码器 → 联合表示
   例: 图像patch + 文本token → 同一个Transformer

2. 晚期融合（Late Fusion）
   各模态 → 各自编码器 → 各自特征 → 融合层 → 联合决策
   例: CLIP(图像编码) + GPT(文本编码) → 对齐

3. 交叉注意力融合（Cross-Attention）
   各模态编码 → 交叉注意力层 → 模态间信息交换
   例: Flamingo, LLaVA

  ┌──────┐  ┌──────┐  ┌──────┐
  │ 文本  │  │ 图像  │  │ 音频  │  ← 输入模态
  └──┬───┘  └──┬───┘  └──┬───┘
     │         │         │
  ┌──▼───┐  ┌──▼───┐  ┌──▼───┐
  │Tokenizer│ │ ViT  │  │Whisper│  ← 模态编码器
  └──┬───┘  └──┬───┘  └──┬───┘
     │         │         │
     └─────────┼─────────┘
               │
        ┌──────▼──────┐
        │  Transformer │  ← 统一的多模态处理
        │  (LLM Core)  │
        └──────┬──────┘
               │
        ┌──────▼──────┐
        │  输出头      │  ← 文本/图像/音频
        └─────────────┘

GPT-4o 的架构思路：
  所有模态 → 统一 token 化 → 同一个大 Transformer → 输出任意模态
""")

