print("\n--- 5. 图像的数字表示 ---")
print("""
计算机中图像本质是数字矩阵：

  灰度图: H × W        （每个像素 0-255）
  彩色图: H × W × 3    （RGB 三通道）

  例如 224×224 的彩色图 = 224 × 224 × 3 = 150,528 个数值

送入 LLM 前的处理：
  1. 文件编码方式：
     - Base64 编码（最常用，适合 API）
     - URL 引用（在线图片）
     - 本地文件路径（本地模型）

  2. 图像预处理：
     - 缩放到模型要求的尺寸
     - 归一化（像素值 0-1 或 -1~1）
     - 分块（大图切分为多个 patch）
""")

