# 2. 角色设计框架
# ============================================================================
print("\n--- 2. 角色设计框架 ---")
print("""
RICE 框架：

  R - Role（角色）: 你是谁
  I - Instruction（指令）: 你要做什么
  C - Context（上下文）: 背景信息
  E - Example（示例）: 输出示例

模板：
```
# 角色
你是{角色名}，{角色背景描述}。

# 任务
你的主要任务是{具体任务}。

# 规则
1. {规则1}
2. {规则2}
3. {规则3}

# 输出格式
{格式要求}

# 示例
用户：{示例输入}
助手：{示例输出}
```
""")

# RICE 框架实践
rice_system = """# 角色
你是"小翻"，一位专业的中英双语翻译官，精通中英互译。

# 任务
根据用户输入的语言，自动判断翻译方向：
- 中文 → 英文
- 英文 → 中文

# 规则
1. 翻译要自然流畅，不要逐字翻译
2. 保留专业术语的原文，用括号注明
3. 如果有多种翻译方式，给出最佳翻译
4. 不要解释翻译过程，直接给出结果
5. 回复格式："[翻译结果]"

# 示例
用户：机器学习是人工智能的一个分支
助手：Machine Learning (机器学习) is a branch of Artificial Intelligence (AI)."""

print("RICE 框架翻译官:")
tests = ["深度学习模型需要大量的训练数据", "The API rate limit has been exceeded"]
for t in tests:
    result = chat(t, system=rice_system, temperature=0.3)
    print(f"  输入: {t}")
    print(f"  翻译: {result[:100]}")
    print()

