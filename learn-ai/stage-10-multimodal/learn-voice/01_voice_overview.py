print("""
数字音频的基本参数：

┌──────────────┬──────────────────────────────────────────┐
│  参数         │  说明                                     │
├──────────────┼──────────────────────────────────────────┤
│  采样率       │  每秒采样次数（Hz）                       │
│              │  8000Hz: 电话  16000Hz: 语音识别常用      │
│              │  44100Hz: CD  48000Hz: 专业音频            │
├──────────────┼──────────────────────────────────────────┤
│  位深度       │  每个采样点的精度（bit）                   │
│              │  16bit: 标准  24bit: 专业  32bit: float   │
├──────────────┼──────────────────────────────────────────┤
│  通道数       │  1=单声道(mono)  2=立体声(stereo)         │
├──────────────┼──────────────────────────────────────────┤
│  时长         │  音频长度（秒）                           │
├──────────────┼──────────────────────────────────────────┤
│  比特率       │  采样率 × 位深 × 通道 = 数据率            │
│              │  16000 × 16 × 1 = 256 kbps               │
└──────────────┴──────────────────────────────────────────┘

常见音频格式：
  WAV:  无压缩，最大，最通用
  MP3:  有损压缩，小，兼容性最好
  FLAC: 无损压缩，中等大小
  OGG:  开源有损压缩
  PCM:  原始采样数据（无文件头）
""")

import numpy as np

# 生成一段模拟音频
sample_rate = 16000
duration = 1.0  # 1秒
t = np.linspace(0, duration, int(sample_rate * duration), endpoint=False)
# 440Hz 正弦波（标准 A 音）
audio = (np.sin(2 * np.pi * 440 * t) * 32767).astype(np.int16)

print(f"模拟音频生成:")
print(f"  采样率: {sample_rate} Hz")
print(f"  时长: {duration} 秒")
print(f"  采样点数: {len(audio)}")
print(f"  数据类型: {audio.dtype}")
print(f"  数据大小: {audio.nbytes} bytes ({audio.nbytes/1024:.1f} KB)")
print(f"  前10个采样值: {audio[:10].tolist()}")

